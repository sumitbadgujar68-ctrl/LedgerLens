import React from 'react';

export type ProvenanceVariant = 'demo' | 'live' | 'ai' | 'analyst' | 'derived' | 'public_source';

const VARIANT_CONFIG: Record<
  ProvenanceVariant,
  { label: string; className: string; title: string }
> = {
  live: {
    label: 'LIVE ON-CHAIN',
    className:
      'bg-emerald-950/60 text-emerald-400 border-emerald-500/30 hover:border-emerald-500/50',
    title: 'Cryptographic data verified against live blockchain node/RPC',
  },
  derived: {
    label: 'DERIVED',
    className:
      'bg-cyan-950/60 text-cyan-400 border-cyan-500/30 hover:border-cyan-500/50',
    title: 'Algorithmically computed from on-chain graph analysis & heuristic rules',
  },
  demo: {
    label: 'DEMO DATA',
    className:
      'bg-amber-950/60 text-amber-400 border-amber-500/30 hover:border-amber-500/50',
    title: 'Synthetic demonstration dataset — not live on-chain ledger activity',
  },
  ai: {
    label: 'AI-GENERATED',
    className:
      'bg-violet-950/60 text-violet-400 border-purple-500/30 hover:border-purple-500/50',
    title: 'Heuristic synthesis generated by Qwen 27B / OpenRouter — verify citations',
  },
  analyst: {
    label: 'ANALYST INPUT',
    className:
      'bg-[var(--color-surface-dim)] text-[var(--color-on-surface-variant)] border-[var(--color-outline)] hover:text-[var(--color-on-surface)]',
    title: 'Manual investigator sworn observation, evidence, or custody annotation',
  },
  public_source: {
    label: 'PUBLIC SOURCE',
    className:
      'bg-blue-500/10 text-blue-400 border-blue-500/30 hover:border-blue-500/50',
    title: 'External public attribution registry or OSINT source',
  },
};

interface ProvenanceBadgeProps {
  variant: ProvenanceVariant | string;
  className?: string;
  size?: 'sm' | 'md';
}

export const ProvenanceBadge: React.FC<ProvenanceBadgeProps> = ({
  variant,
  className = '',
  size = 'sm',
}) => {
  const normalizedKey: ProvenanceVariant =
    variant === 'live' || variant === 'live_onchain'
      ? 'live'
      : variant === 'derived'
      ? 'derived'
      : variant === 'ai' || variant === 'ai_generated'
      ? 'ai'
      : variant === 'analyst' || variant === 'analyst_note' || variant === 'analyst_input'
      ? 'analyst'
      : variant === 'public_source' || variant === 'public'
      ? 'public_source'
      : 'demo';

  const config = VARIANT_CONFIG[normalizedKey];
  const sizeClasses =
    size === 'sm'
      ? 'px-2 py-0.5 text-[10px] tracking-wider'
      : 'px-2.5 py-1 text-[11px] tracking-wider';

  return (
    <span
      title={config.title}
      className={`inline-flex items-center font-bold rounded-lg border uppercase select-none transition-colors ${sizeClasses} ${config.className} ${className}`}
    >
      {config.label}
    </span>
  );
};
